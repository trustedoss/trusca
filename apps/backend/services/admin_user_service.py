async def list_users(
    session: AsyncSession,
    *,
    actor: CurrentUser,  # noqa: ARG001 — kept for symmetry with other admin services
    page: int = 1,
    page_size: int = 50,
    role: str | None = None,
    active: bool | None = None,
    search: str | None = None,
) -> AdminUserListPage:
    """
    Return a page of users (paginated, filterable).

    - ``role`` filters by highest-effective role (super_admin = is_superuser;
      team_admin / developer = exists membership with that role; the filter
      is a coarse "user has at least one membership of this kind"). When
      role is ``super_admin`` we filter on ``is_superuser=true`` directly.
    - ``active`` filters by ``is_active`` exactly.
    - ``search`` is bounded substring ILIKE on email or full_name (max 255
      chars to bound the query cost).
    """
    page = max(page, 1)
    page_size = max(min(page_size, 200), 1)

    # People only. A service account in the user list would invite the actions
    # this list offers, and those actions are wrong for it: there is nobody to
    # email a reset to, and deactivating it from here is a pipeline outage that
    # reads on screen as tidying up a leaver. Service accounts are managed on
    # the integrations page, next to the keys they hold.
    base = select(User).where(User.is_service_account.is_(False))
    count_base = (
        select(func.count())
        .select_from(User)
        .where(User.is_service_account.is_(False))
    )

    if active is not None:
        base = base.where(User.is_active.is_(active))
        count_base = count_base.where(User.is_active.is_(active))

    if role == "super_admin":
        base = base.where(User.is_superuser.is_(True))
        count_base = count_base.where(User.is_superuser.is_(True))
    elif role in ("team_admin", "developer", "viewer"):
        sub = select(Membership.user_id).where(Membership.role == role).scalar_subquery()
        base = base.where(User.id.in_(sub))
        count_base = count_base.where(User.id.in_(sub))

    if search and search.strip():
        # Bounded substring search; the inputs are already capped at 255 in
        # the route layer (Query(max_length=255)). Search is intentionally
        # case-insensitive on email (CITEXT-friendly) and full_name.
        # Wildcards are escaped so a literal '%' cannot widen the match to
        # every user in the deployment (S1-2).
        like = f"%{escape_like(search.strip())}%"
        predicate = or_(
            User.email.ilike(like, escape="\\"),
            User.full_name.ilike(like, escape="\\"),
        )
        base = base.where(predicate)
        count_base = count_base.where(predicate)

    total = int((await session.execute(count_base)).scalar_one())

    rows_stmt = (
        base.order_by(User.created_at.desc(), User.id.desc())
        .limit(page_size)
        .offset((page - 1) * page_size)
    )
    rows = list((await session.execute(rows_stmt)).scalars().all())

    # H-2: membership rollup for the page (one aggregate query, not N) so the
    # list can render the effective role + team count without the drawer.
    rollup: dict[uuid.UUID, tuple[int, bool]] = {}
    user_ids = [u.id for u in rows]
    if user_ids:
        agg = await session.execute(
            select(
                Membership.user_id,
                func.count(Membership.id),
                func.bool_or(Membership.role == "team_admin"),
            )
            .where(Membership.user_id.in_(user_ids))
            .group_by(Membership.user_id)
        )
        for uid, member_count, has_team_admin in agg.all():
            rollup[uid] = (int(member_count), bool(has_team_admin))

    def _effective_role(u: User) -> str:
        if u.is_superuser:
            return "super_admin"
        _, has_team_admin = rollup.get(u.id, (0, False))
        return "team_admin" if has_team_admin else "developer"

    items = [
        AdminUserListItem(
            id=u.id,
            email=u.email,
            full_name=u.full_name,
            is_active=u.is_active,
            is_superuser=u.is_superuser,
            role=_effective_role(u),  # type: ignore[arg-type]
            team_count=rollup.get(u.id, (0, False))[0],
            last_login_at=u.last_login_at,
            created_at=u.created_at,
        )
        for u in rows
    ]

    return AdminUserListPage(
        items=items,
        total=total,
        page=page,
        page_size=page_size,
    )


