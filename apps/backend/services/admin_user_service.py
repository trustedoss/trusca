async def update_user_role(
    session: AsyncSession,
    *,
    actor: CurrentUser,
    user_id: uuid.UUID,
    payload: AdminUserRoleUpdate,
) -> AdminUserDetail:
    """
    Set the user's role.

    Semantics:
      - ``role == "super_admin"`` -> ``user.is_superuser = True``. Existing
        memberships are not touched (the super_admin role is global; team
        memberships are independent).
      - ``role in {"team_admin", "developer"}`` -> ``user.is_superuser = False``
        AND upsert ``Membership(user_id, team_id, role)``. ``team_id`` is
        required.

    Safety: rejects (422) when the change would demote the last active
    super_admin or when the actor is the target user.
    """
    if user_id == actor.id:
        raise CannotModifySelf("cannot modify your own role")

    user = await _load_user_with_memberships(session, user_id)

    target_role = payload.role
    target_team_id = payload.team_id

    if target_role == "super_admin":
        # Promotion to super_admin (or no-op if already super_admin).
        user.is_superuser = True
        user.updated_at = _now()
    else:
        if target_team_id is None:
            raise InvalidRoleAssignment("team_id is required when role is team_admin or developer")

        # F9 — preflight: the team must exist BEFORE we let the membership
        # insert race a deleted-team CASCADE. The IntegrityError catch on
        # commit is the second-line defence for the rare delete-during-
        # commit window, but the preflight catches the common "stale UUID"
        # case at a clean boundary with no rollback noise.
        team_exists = (
            await session.execute(select(Team.id).where(Team.id == target_team_id))
        ).scalar_one_or_none()
        if team_exists is None:
            raise TeamNotFound(
                f"team {target_team_id} does not exist",
                team_id=target_team_id,
            )

        # If we are demoting *from* super_admin, make sure we are not
        # removing the last lockout-prevention seat. Take a row-level lock
        # on the entire active-super-admin set BEFORE the count check so
        # two concurrent demote requests serialize through Postgres
        # instead of both passing an optimistic ``count > 1`` check
        # (CWE-367 TOCTOU; see _lock_and_count_active_super_admins).
        if user.is_superuser:
            count = await _lock_and_count_active_super_admins(session)
            # The user being demoted is counted; demoting them takes the
            # count to (count - 1). Reject when that would hit zero.
            if user.is_active and count <= 1:
                raise LastSuperAdminProtected("cannot demote the last active super_admin")
            user.is_superuser = False

        # Upsert the membership row.
        existing = next(
            (m for m in user.memberships if m.team_id == target_team_id),
            None,
        )
        if existing is None:
            session.add(
                Membership(
                    user_id=user.id,
                    team_id=target_team_id,
                    role=target_role,
                )
            )
        else:
            existing.role = target_role
            existing.updated_at = _now()

        user.updated_at = _now()

    try:
        await session.commit()
    except IntegrityError as exc:
        # F9 — race window: the team was deleted between our preflight
        # SELECT and the membership INSERT. The FK CASCADE on team delete
        # would normally take both rows together, but the membership row
        # we're inserting was not present at that point. Translate the FK
        # violation to a 422 with the same Problem Details shape as the
        # preflight. Other IntegrityErrors (uniqueness on the membership
        # PK, etc.) re-raise — those are real bugs, not user errors.
        await session.rollback()
        if target_team_id is not None and _is_team_fk_violation(exc):
            raise TeamNotFound(
                f"team {target_team_id} does not exist",
                team_id=target_team_id,
            ) from exc
        # A5 (sys-bug-u&t-1) — depth-in-defence: the application guard
        # (_lock_and_count_active_super_admins above) should always trip
        # first under normal flow. The DB trigger from migration 0013
        # only fires when something bypasses that guard (e.g. a future
        # endpoint that forgets to call the locking count). Translate the
        # 23514 to the same Problem Details shape so the API contract is
        # invariant of which layer caught the bypass.
        if _is_last_super_admin_violation(exc):
            raise LastSuperAdminProtected(
                "cannot demote the last active super_admin"
            ) from exc
        raise
    # Their grade just changed, so any principal cached from the old one is
    # wrong. Bounded by the lifetime either way; this is what makes the
    # administrator's own next request show the new grade.
    forget_principal(user_id)
    log.info(
        "admin.user.role_changed",
        actor_id=str(actor.id),
        target_user_id=str(user_id),
        new_role=target_role,
        team_id=str(target_team_id) if target_team_id else None,
    )

    # Reload with memberships for the response.
    return await get_user_detail(session, actor=actor, user_id=user_id)


